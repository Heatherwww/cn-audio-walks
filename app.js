function mergeAudioAssetManifest(manifest) {
  if (!manifest?.routes) return;
  audioAssetManifest = {
    ...audioAssetManifest,
    ...manifest,
    routes: {
      ...audioAssetManifest.routes,
      ...manifest.routes
    }
  };
}

function loadAudioAssetManifest() {
  if (typeof fetch !== "function") return;
  fetch("audio-assets/manifest.json", { cache: "no-cache" })
    .then((response) => (response.ok ? response.json() : null))
    .then((manifest) => {
      if (!manifest) return;
      mergeAudioAssetManifest(manifest);
      render();
    })
    .catch(() => {});
}

function buildRouteIntroSegments(route, startIndex = 0) {
  const safeStartIndex = Math.max(0, Math.min(route.stops.length - 1, startIndex));
  const firstStop = route.stops[safeStartIndex];
  const finalStop = route.stops[route.stops.length - 1];
  const startLabel = safeStartIndex === 0
    ? route.start
    : `第 ${safeStartIndex + 1} 站：${firstStop.title}`;
  const scopeLabel = safeStartIndex === 0 ? "整条路线" : "剩余路线";
  return [
    {
      minute: 0,
      label: "开场站位",
      text: `这条路线是${route.title}。先确认你现在站在${startLabel}。不要急着往前走，先把手机音量调到能听清路口声音的程度。`
    },
    {
      minute: 1,
      label: "路线看法",
      text: `接下来会听${scopeLabel}，终点是${route.end}，全线约${route.distance}，建议游览${visitDurationLabel(route)}，语音覆盖${audioDurationLabel(route)}。${route.mapNote}`
    },
    {
      minute: 2,
      label: "第一步",
      text: `路线主题是${route.theme}。正式开始前请先确认这一站：${firstStop.title}，站位是${firstStop.location}。听完每一站后，我都会告诉你下一步怎么走，最后会在${finalStop.title}收束。`
    }
  ];
}

function routeIntroDurationMinutes(route, startIndex = 0) {
  const segments = buildRouteIntroSegments(route, startIndex);
  const last = segments[segments.length - 1];
  return (last?.minute || 0) + 1;
}

function routeIntroDurationLabel(route, startIndex = 0) {
  return `约 ${routeIntroDurationMinutes(route, startIndex)} 分钟`;
}

