function routeQualitySummary(route) {
  const visit = visitMinutes(route);
  const audio = audioMinutes(route);
  const stopCount = route.stops.length;
  const anchorCount = route.stops.filter((_, index) => contentAnchorForStop(route, index).length >= 24).length;
  const dwellCount = route.stops.reduce(
    (sum, stop, index) => sum + pauseSegmentsForStop(route, stop, index).length,
    0
  );
  const introCount = buildRouteIntroSegments(route).length;
  const mapReady =
    mobileMapContext(route) !== `${route.start} · ${route.end}` &&
    !mapBackdrop(route.id).includes("map-terrace");

  return [
    {
      label: "时长覆盖",
      value: `${audio}/${visit} 分钟`,
      detail: audio >= visit ? "语音不短于建议游览" : "需要补长语音",
      ok: audio >= visit
    },
    {
      label: "驻足留白",
      value: `${dwellCount} 段`,
      detail: `平均每站 ${Math.round(dwellCount / stopCount)} 段`,
      ok: dwellCount >= stopCount * 2
    },
    {
      label: "锚点覆盖",
      value: `${anchorCount}/${stopCount}`,
      detail: "点位现场锚点",
      ok: anchorCount === stopCount
    },
    {
      label: "路线开场",
      value: routeIntroDurationLabel(route),
      detail: `${introCount} 段开场`,
      ok: introCount === 3
    },
    {
      label: "手绘地图",
      value: mapReady ? "专属" : "待补",
      detail: "桌面和手机语境",
      ok: mapReady
    },
    {
      label: "点位链路",
      value: `${stopCount} 点`,
      detail: "含下一站指令",
      ok: route.stops.every((stop) => Boolean(stop.next))
    }
  ];
}

