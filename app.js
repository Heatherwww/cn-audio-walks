function audioPlaybackAsset(route, index = state.stopIndex, mode = state.playbackMode) {
  const assets = routeAudioAssets(route);
  if (!assets) return null;
  if (mode === "intro") return assets.intro || null;
  return assets.stops?.[index] || null;
}

function audioAssetCount(route) {
  const assets = routeAudioAssets(route);
  if (!assets) return 0;
  return Number(Boolean(assets.intro)) + Object.keys(assets.stops || {}).length;
}

function audioAssetSummary() {
  return routeEntries().reduce(
    (summary, { route }) => {
      const routeAssets = audioAssetCount(route);
      if (routeAssets > 0) summary.routes += 1;
      summary.assets += routeAssets;
      return summary;
    },
    { routes: 0, assets: 0 }
  );
}

