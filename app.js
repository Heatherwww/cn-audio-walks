function buildRouteScriptPackage(city, route) {
  const sourceNote = sourceNoteForRoute(route);
  const lines = [
    `${city.name} · ${route.title}`,
    `主题：${route.theme}`,
    `建议游览：${visitDurationLabel(route)}`,
    `语音覆盖：${audioDurationLabel(route)}`,
    `路线：${route.start} → ${route.end}`,
    `说明：${route.mapNote}`,
    sourceNote ? `资料锚点：${sourceNote}` : "",
    ""
  ].filter((line, index, arr) => line || index === arr.length - 1);

  lines.push("路线开场");
  lines.push(`开场语音：${routeIntroDurationLabel(route)}`);
  buildRouteIntroSegments(route).forEach((segment) => {
    lines.push(`${formatMinuteMark(segment.minute)} ${segment.label}`);
    lines.push(segment.text);
  });
  lines.push("");

  route.stops.forEach((stop, index) => {
    const anchor = contentAnchorForStop(route, index);
    lines.push(`第 ${index + 1} 站：${stop.title}`);
    lines.push(`站位：${stop.location}`);
    lines.push(`朝向：${stop.cue}`);
    if (anchor) lines.push(`现场锚点：${anchor}`);
    lines.push(`本点语音：${stopAudioDurationLabel(route, index)}`);
    buildStopAudioSegments(route, stop, index).forEach((segment) => {
      lines.push(`${formatMinuteMark(segment.minute)} ${segment.label}${segment.isPause ? " [留白]" : ""}`);
      lines.push(segment.text);
    });
    lines.push(`下一步：${stop.next}`);
    lines.push("");
  });

  return lines.join("\n");
}

function buildAudioProductionManifest() {
  const routes = routeEntries();
  const routeRecords = routes.map(({ city, route }) => {
    const quality = routeQualitySummary(route);
    const stops = route.stops.map((stop, index) => {
      const segments = buildStopAudioSegments(route, stop, index);
      return {
        stopNumber: index + 1,
        title: stop.title,
        location: stop.location,
        cue: stop.cue,
        audioMinutes: stopAudioMinutes(route, index),
        segmentCount: segments.length,
        dwellPauseCount: segments.filter((segment) => segment.isPause).length,
        hasAudioAsset: Boolean(audioPlaybackAsset(route, index, "stop")),
        anchor: contentAnchorForStop(route, index),
        next: stop.next
      };
    });

    return {
      cityId: city.id,
      cityName: city.name,
      routeId: route.id,
      routeTitle: route.title,
      theme: route.theme,
      start: route.start,
      end: route.end,
      distance: route.distance,
      suggestedVisitMinutes: visitMinutes(route),
      plannedAudioMinutes: audioMinutes(route),
      routeIntroMinutes: routeIntroDurationMinutes(route),
      hasRouteIntroAudioAsset: Boolean(audioPlaybackAsset(route, 0, "intro")),
      realAudioAssetCount: audioAssetCount(route),
      stopCount: route.stops.length,
      sourceNote: sourceNoteForRoute(route),
      readyForAudioDraft: quality.every((item) => item.ok),
      quality,
      stops
    };
  });

  return {
    title: "中国耳游音频制作清单",
    publicPreviewUrl: "https://cn-audio-walks.chinaaudioguide.workers.dev/",
    cityCount: data.cities.length,
    routeCount: routeRecords.length,
    stopCount: routeRecords.reduce((sum, route) => sum + route.stopCount, 0),
    plannedAudioMinutes: routeRecords.reduce((sum, route) => sum + route.plannedAudioMinutes, 0),
    routeIntroMinutes: routeRecords.reduce((sum, route) => sum + route.routeIntroMinutes, 0),
    realAudioAssetCount: routeRecords.reduce((sum, route) => sum + route.realAudioAssetCount, 0),
    realAudioRouteCount: routeRecords.filter((route) => route.realAudioAssetCount > 0).length,
    routes: routeRecords
  };
}

