function renderMap(route) {
  const path = routePath(route.stops);
  const viewBox = routeViewBox(route);
  const currentStop = route.stops[state.stopIndex];
  const hereX = Math.min(820, currentStop.xy[0] + 34);
  const hereY = Math.max(76, currentStop.xy[1] - 42);
  const first = route.stops[0].xy;
  const second = route.stops[1] ? route.stops[1].xy : [first[0], first[1] + 1];
  const dirX = first[0] - second[0];
  const dirY = first[1] - second[1];
  const dirLen = Math.hypot(dirX, dirY) || 1;
  const introX = Math.max(56, Math.min(904, first[0] + (dirX / dirLen) * 58));
  const introY = Math.max(82, Math.min(616, first[1] + (dirY / dirLen) * 58));
  const labels = route.stops
    .map((stop, index) => {
      const active = index === state.stopIndex && !state.introSelected ? " active" : "";
      const yLabel = stop.xy[1] > 610 ? stop.xy[1] - 38 : stop.xy[1] + 44;
      return `
        <g class="poi-button${active}" role="button" tabindex="0" data-stop="${index}" onclick="selectStopAndPlay(${index})" aria-label="${stop.title}">
          <circle cx="${stop.xy[0]}" cy="${stop.xy[1]}" r="21"></circle>
          <text x="${stop.xy[0]}" y="${stop.xy[1] + 1}">${index + 1}</text>
        </g>
        <text class="poi-label" x="${stop.xy[0] + 28}" y="${yLabel}">${stop.title}</text>
      `;
    })
    .join("");

  return `
    <svg class="route-map" viewBox="${viewBox.value}" role="img" aria-label="${route.title}路线地图">
      <rect x="0" y="0" width="960" height="680" fill="#eef3ed"></rect>
      <g class="map-compass">
        <path d="M844 126 l18 -34 l18 34 l-18 -8Z"></path>
        <text x="862" y="152">N</text>
      </g>
      <g class="map-drawing" transform="translate(0 -170)">
        ${mapBackdrop(route.id)}
        <path class="route-line-shadow" d="${path}"></path>
        <path class="route-line" d="${path}"></path>
        <path class="route-line-dash" d="${path}"></path>
        ${labels}
        <g class="poi-button intro-point${state.introSelected ? " active" : ""}" role="button" tabindex="0" data-intro onclick="selectIntroAndPlay()" aria-label="路线开场">
          <circle cx="${introX}" cy="${introY}" r="19"></circle>
          <text x="${introX}" y="${introY + 1}">起</text>
        </g>
        <text class="poi-label" x="${introX + 26}" y="${introY + 5}">路线开场</text>
        <g class="map-here">
          <path d="M${hereX} ${hereY} h92 a18 18 0 0 1 18 18 v0 a18 18 0 0 1 -18 18 h-92 a18 18 0 0 1 -18 -18 v0 a18 18 0 0 1 18 -18Z"></path>
          <text x="${hereX + 46}" y="${hereY + 19}">你在这里</text>
        </g>
      </g>
      <text class="map-note" x="${viewBox.noteX}" y="${viewBox.noteY}">${route.start} → ${route.end}</text>
    </svg>
  `;
}

