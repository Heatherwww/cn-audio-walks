function audioConstructor() {
  if (typeof window !== "undefined" && typeof window.Audio === "function") return window.Audio;
  if (typeof Audio === "function") return Audio;
  return null;
}

function cleanupAudioElement() {
  if (!state.audioElement) {
    state.audioAsset = null;
    return;
  }
  try {
    state.audioElement.pause();
    state.audioElement.removeAttribute?.("src");
    state.audioElement.load?.();
  } catch {
    // Ignore cleanup failures; stopping playback should remain best-effort.
  }
  state.audioElement = null;
  state.audioAsset = null;
}

function playAudioAsset(asset, options) {
  if (!asset?.src) return false;
  const AudioCtor = audioConstructor();
  if (!AudioCtor) return false;

  window.speechSynthesis?.cancel();
  clearVoiceTimers();
  cleanupAudioElement();

  const audio = new AudioCtor(asset.src);
  state.audioElement = audio;
  state.audioAsset = asset;
  state.audioSourceMode = "asset";
  state.isPlaying = true;
  state.routeTourCompleted = false;
  state.playbackMode = options.mode;
  state.progress = 0;
  state.playStartedAt = Date.now();
  state.playDurationSeconds = asset.durationSeconds || options.durationSeconds;
  state.activeSegmentIndex = 0;
  audio.playbackRate = state.playbackRate;
  ensureMusicElement();
  syncMusicPlayback();

  const routeId = options.route.id;
  const stopIndex = options.stopIndex;
  const isIntro = options.mode === "intro";
  audio.preload = "auto";
  audio.addEventListener?.("ended", () => {
    if (isIntro) finishIntroPlayback(routeId, stopIndex);
    else finishStopPlayback(routeId, stopIndex);
  });
  audio.addEventListener?.("error", () => {
    const fallback = options.fallback;
    cleanupAudioElement();
    if (typeof fallback === "function") fallback();
  });

  window.clearInterval(state.tick);
  state.tick = window.setInterval(() => {
    const elapsedSeconds = playbackElapsedSeconds();
    state.progress = Math.min(100, (elapsedSeconds / state.playDurationSeconds) * 100);
    state.activeSegmentIndex = isIntro
      ? activeSegmentIndexForSegments(buildRouteIntroSegments(options.route, stopIndex))
      : activeSegmentIndexForElapsed(options.route, options.route.stops[stopIndex], stopIndex);
    updateProgressOnly();
    updatePlaybackStatusOnly();
  }, 1000);

  const playAttempt = audio.play?.();
  if (playAttempt?.catch) {
    playAttempt.catch(() => {
      const fallback = options.fallback;
      cleanupAudioElement();
      if (typeof fallback === "function") fallback();
    });
  }

  render();
  return true;
}

